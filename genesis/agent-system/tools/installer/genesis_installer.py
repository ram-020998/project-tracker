"""Genesis agent installer (Phase 47, 47-07). Stdlib only.

Renders agent-system/{agents,skills,hooks} (placeholders -> absolute paths), validates the result with its OWN checks
(`kiro-cli agent validate` is lenient — 47-06 As-built), shows a plan (added / changed / removed / unchanged, with
unified diffs), then applies it: atomic writes, backups of everything replaced or removed, and a manifest
(`{{GENESIS_HOME}}/install.json`) listing every installed file + sha256. It never touches a file it does not own: an
existing destination that is not in the manifest (a file you made yourself) is refused unless --force, which backs it
up first.

Exit codes: 0 ok / nothing to do, 1 refused (preflight, validation or a foreign file), 2 usage/config error.
"""
