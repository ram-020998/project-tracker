from pathlib import Path

SOURCE_DEFAULT = Path(__file__).resolve().parents[2]  # .../agent-system
DEFAULT_REPOS = "/Users/ramaswamy.u/repo-gitlab/ramaswamy.u"
# The five Genesis code repos under {{REPOS}} (47-02 §3; same list as genesis_ctx.config.REPO_NAMES).
REPO_NAMES = ("genesis", "genesis-core", "genesis-workflows", "kiro-agent-sdk", "genesis-appian-parser")
CONF_KEYS = ("TRACKER", "REPOS", "GENESIS_HOME", "MODEL")
PLACEHOLDER = re.compile(r"\{\{[A-Z][A-Z0-9_]*\}\}")
MANIFEST_VERSION = 1

# What the installer accepts in a profile. Deliberately strict — extend on purpose, not by accident.
KNOWN_TOOLS = {"read", "write", "shell", "web", "subagent", "code"}  # V3 tool tags (47-06 As-built §3; S5b probe)
KNOWN_CAPABILITIES = {"fs_read", "fs_write", "shell"}
EFFECTS = {"allow", "deny", "ask"}
TRIGGERS = {"SessionStart", "UserPromptSubmit", "PreToolUse", "PostToolUse", "Stop", "PreTaskExec", "PostTaskExec",
            "PostFileCreate", "PostFileSave", "PostFileDelete"}
RESOURCE_SCHEMES = ("file://", "skill://")
AGENT_SUFFIXES = (".json", ".md", ".yaml", ".yml")  # a same-name agent in any of these would collide
SKIP_NAMES = {".DS_Store", "__pycache__", ".gitkeep"}

SHIM = """#!/usr/bin/env bash
# genesis-ctx shim — generated by the Genesis installer (47-07). Runs the context compiler from its
# project-tracker source, so tool fixes apply without a reinstall. Do not edit: update.sh rewrites it.
exec "{{TRACKER}}/agent-system/tools/genesis-ctx" "$@"
"""


class InstallError(Exception):
    """A usage/config problem (exit 2)."""


# ── configuration ──────────────────────────────────────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class Config:
    source: Path        # agent-system/ (agents, skills, hooks)
    tracker: Path       # project-tracker/genesis
    repos: Path
    home: Path          # {{GENESIS_HOME}}
    agents_dir: Path    # ~/.kiro/agents
    model: str          # "" = keep the profile's own value

    @property
    def manifest_path(self) -> Path:
        return self.home / "install.json"

    def values(self) -> dict[str, str]:
        return {"TRACKER": str(self.tracker), "REPOS": str(self.repos), "GENESIS_HOME": str(self.home),
                "MODEL": self.model}


def parse_conf(text: str) -> dict[str, str]:
    """KEY=VALUE lines; '#' starts a comment (whole line, or after whitespace)."""
    out: dict[str, str] = {}
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            raise InstallError(f"install.conf line {n}: expected KEY=VALUE, got {raw!r}")
        key, value = line.split("=", 1)
        key = key.strip()
        value = re.split(r"\s+#", value, maxsplit=1)[0].strip().strip('"').strip("'")
        if key not in CONF_KEYS:
            raise InstallError(f"install.conf line {n}: unknown key {key!r} (known: {', '.join(CONF_KEYS)})")
        out[key] = value
    return out


def _abs(key: str, value: str) -> Path:
    p = Path(value).expanduser()
    if not p.is_absolute():
        raise InstallError(f"{key} must be an absolute path (got {value!r})")
    return Path(os.path.normpath(p))


def load_config(source: Path | None = None, conf: Path | None = None) -> Config:
    source = (source or SOURCE_DEFAULT).resolve()
    conf = conf or source / "install.conf"
    values: dict[str, str] = {}
    if conf.is_file():
        values = parse_conf(conf.read_text(encoding="utf-8"))
    tracker = _abs("TRACKER", values.get("TRACKER") or str(source.parent))
    repos = _abs("REPOS", values.get("REPOS") or DEFAULT_REPOS)
    home = _abs("GENESIS_HOME", values.get("GENESIS_HOME") or str(Path.home() / ".kiro" / "genesis"))
    return Config(source=source, tracker=tracker, repos=repos, home=home,
                  agents_dir=Path.home() / ".kiro" / "agents", model=values.get("MODEL", ""))


# ── render ─────────────────────────────────────────────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class Item:
    data: bytes
    mode: int
    source: str     # path relative to agent-system/, or "generated"
    text: bool      # rendered (utf-8) vs copied verbatim


def render_text(text: str, values: dict[str, str]) -> str:
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    return text


def _render_file(path: Path, rel: str, mode: int, values: dict[str, str]) -> Item:
    raw = path.read_bytes()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return Item(raw, mode, rel, False)
    return Item(render_text(text, values).encode("utf-8"), mode, rel, True)


def _files(root: Path):
    for p in sorted(root.rglob("*")):
        if p.is_file() and not (set(p.relative_to(root).parts) & SKIP_NAMES):
            yield p


def build_desired(cfg: Config) -> dict[Path, Item]:
    """Every file the installation should contain, rendered in memory, keyed by absolute destination."""
    values = cfg.values()
    out: dict[Path, Item] = {}
    agents = cfg.source / "agents"
    for p in sorted(agents.glob("genesis-*.json")):
        item = _render_file(p, f"agents/{p.name}", 0o644, values)
        if cfg.model:
            try:
                obj = json.loads(item.data)
                obj["model"] = cfg.model
                item = Item((json.dumps(obj, indent=2, ensure_ascii=False) + "\n").encode("utf-8"),
                            item.mode, item.source, True)
            except ValueError:
                pass  # reported by validate()
        out[cfg.agents_dir / p.name] = item
    for d in sorted((cfg.source / "skills").glob("genesis-*")):
        if not d.is_dir():
            continue
        for p in _files(d):
            rel = p.relative_to(cfg.source / "skills")
            mode = 0o755 if os.access(p, os.X_OK) else 0o644
            out[cfg.home / "skills" / rel] = _render_file(p, f"skills/{rel}", mode, values)
    for p in sorted((cfg.source / "hooks").glob("*.sh")):
        out[cfg.home / "hooks" / p.name] = _render_file(p, f"hooks/{p.name}", 0o755, values)
    out[cfg.home / "bin" / "genesis-ctx"] = Item(render_text(SHIM, values).encode("utf-8"), 0o755, "generated", True)
    return out


# ── validate (the installer's own gate) ────────────────────────────────────────────────────────────────────────


def _frontmatter(text: str) -> dict[str, str] | None:
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end < 0:
        return None
    fm: dict[str, str] = {}
    for line in text[4:end].splitlines():
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m:
            fm[m.group(1)] = m.group(2).strip().strip('"').strip("'")
    return fm


def validate(cfg: Config, desired: dict[Path, Item]) -> list[str]:
    errors: list[str] = []

    def exists(p: Path) -> bool:
        return p in desired or p.exists()

    def executable(p: Path) -> bool:
        if p in desired:
            return bool(desired[p].mode & 0o111)
        return p.is_file() and os.access(p, os.X_OK)

    def show(p: Path) -> str:
        return _tilde(p)

    for dest, item in desired.items():
        if item.text:
            left = sorted(set(PLACEHOLDER.findall(item.data.decode("utf-8"))))
            if left:
                errors.append(f"{show(dest)}: unrendered placeholder(s) {', '.join(left)}")

    agent_names = {d.stem for d in desired if d.parent == cfg.agents_dir}
    if not agent_names:
        errors.append(f"no agents/genesis-*.json profiles under {cfg.source}")
    other_agents = {p.stem for p in cfg.agents_dir.glob("*") if p.suffix in AGENT_SUFFIXES} \
        if cfg.agents_dir.is_dir() else set()

    for dest, item in sorted(desired.items()):
        if dest.parent != cfg.agents_dir:
            continue
        where = f"agents/{dest.name}"
        try:
            prof = json.loads(item.data)
        except ValueError as e:
            errors.append(f"{where}: not valid JSON after rendering ({e})")
            continue
        if not isinstance(prof, dict):
            errors.append(f"{where}: top level must be an object")
            continue
        if prof.get("name") != dest.stem:
            errors.append(f"{where}: name {prof.get('name')!r} must equal the file name {dest.stem!r}")
        for key in ("description", "prompt"):
            if not isinstance(prof.get(key), str) or not prof[key].strip():
                errors.append(f"{where}: {key} must be a non-empty string")
        if "model" in prof and (not isinstance(prof["model"], str) or not prof["model"].strip()):
            errors.append(f"{where}: model, when present, must be a non-empty string")
        tools = prof.get("tools")
        if not isinstance(tools, list) or not all(isinstance(t, str) for t in tools):
            errors.append(f"{where}: tools must be a list of strings")
        else:
            for t in tools:
                if t not in KNOWN_TOOLS:
                    errors.append(f"{where}: unknown tool {t!r} (known: {', '.join(sorted(KNOWN_TOOLS))})")
        for r in prof.get("resources") or []:
            scheme = next((s for s in RESOURCE_SCHEMES if isinstance(r, str) and r.startswith(s)), None)
            if scheme is None:
                errors.append(f"{where}: resource {r!r} must start with file:// or skill://")
                continue
            p = Path(r[len(scheme):])
            if not p.is_absolute():
                errors.append(f"{where}: resource {r!r} must be an absolute path (D3)")
            elif _under(p, cfg.home) and p not in desired:
                errors.append(f"{where}: resource {r!r} is not part of this installation")
            elif not exists(p):
                errors.append(f"{where}: resource {r!r} does not exist")
            elif scheme == "skill://" and p.name != "SKILL.md":
                errors.append(f"{where}: skill resource {r!r} must point at a SKILL.md")
            elif scheme == "skill://" and str(p) not in str(prof.get("prompt") or ""):
                # KAS 0.66.43 registers profile skills only when a session is CREATED in the agent's mode;
                # `kiro-cli --v3 chat --agent X` creates it as vibe and then switches, so the skill tool may not
                # list them. The prompt therefore names every skill by absolute path (read it directly) — S5b.
                errors.append(f"{where}: skill {p.parent.name} is not named by path in the prompt "
                              "(the read-it-directly fallback)")
        perms = prof.get("permissions")
        rules = perms.get("rules") if isinstance(perms, dict) else None
        if not isinstance(rules, list) or not rules:
            errors.append(f"{where}: permissions.rules is required (V3 skips profiles without it)")
            rules = []
        for i, rule in enumerate(rules):
            if not isinstance(rule, dict):
                errors.append(f"{where}: permissions.rules[{i}] must be an object")
                continue
            if rule.get("capability") not in KNOWN_CAPABILITIES:
                errors.append(f"{where}: permissions.rules[{i}] unknown capability {rule.get('capability')!r}")
            if rule.get("effect") not in EFFECTS:
                errors.append(f"{where}: permissions.rules[{i}] effect must be one of {sorted(EFFECTS)}, "
                              f"got {rule.get('effect')!r}")
            m = rule.get("match")
            if not isinstance(m, list) or not m or not all(isinstance(x, str) and x for x in m):
                errors.append(f"{where}: permissions.rules[{i}] match must be a non-empty list of strings")
        for i, hook in enumerate(prof.get("hooks") or []):
            label = f"{where}: hooks[{i}]"
            if not isinstance(hook, dict):
                errors.append(f"{label} must be an object")
                continue
            if hook.get("trigger") not in TRIGGERS:
                errors.append(f"{label} unknown trigger {hook.get('trigger')!r}")
            action = hook.get("action") if isinstance(hook.get("action"), dict) else {}
            if action.get("type") != "command" or not isinstance(action.get("command"), str):
                errors.append(f"{label} action must be {{type: command, command: <string>}}")
                continue
            try:
                exe = shlex.split(action["command"])[0]
            except (ValueError, IndexError):
                errors.append(f"{label} command {action['command']!r} cannot be parsed")
                continue
            p = Path(exe)
            if not p.is_absolute():
                errors.append(f"{label} command {exe!r} must be an absolute path (agent shells have no PATH setup)")
            elif not exists(p):
                errors.append(f"{label} command {exe!r} does not exist")
            elif not executable(p):
                errors.append(f"{label} command {exe!r} is not executable")
        sub = (prof.get("toolsSettings") or {}).get("subagent") or {}
        for key in ("availableAgents", "trustedAgents"):
            for name in sub.get(key) or []:
                if name not in agent_names and name not in other_agents:
                    errors.append(f"{where}: toolsSettings.subagent.{key} names unknown agent {name!r}")

    skill_dirs = sorted({d.relative_to(cfg.home / "skills").parts[0] for d in desired
                         if _under(d, cfg.home / "skills")})
    for name in skill_dirs:
        p = cfg.home / "skills" / name / "SKILL.md"
        if p not in desired:
            errors.append(f"skills/{name}: SKILL.md missing")
            continue
        fm = _frontmatter(desired[p].data.decode("utf-8"))
        if fm is None:
            errors.append(f"skills/{name}/SKILL.md: no '---' frontmatter")
            continue
        for key in ("name", "description"):
            if not fm.get(key):
                errors.append(f"skills/{name}/SKILL.md: frontmatter {key} missing or empty")
        if fm.get("name") and fm["name"] != name:
            errors.append(f"skills/{name}/SKILL.md: name {fm['name']!r} must equal the directory name")

    for dest, item in desired.items():
        if dest.parent in (cfg.home / "hooks", cfg.home / "bin") and not item.data.startswith(b"#!"):
            errors.append(f"{show(dest)}: missing #! line")
    return errors


# ── manifest + plan ────────────────────────────────────────────────────────────────────────────────────────────


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _under(p: Path, root: Path) -> bool:
    try:
        p.relative_to(root)
        return True
    except ValueError:
        return False


def _tilde(p: Path) -> str:
    home = Path.home()
    return "~/" + str(p.relative_to(home)) if _under(p, home) else str(p)


def read_manifest(cfg: Config) -> dict | None:
    try:
        data = json.loads(cfg.manifest_path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None
    except ValueError as e:
        raise InstallError(f"{cfg.manifest_path} is not valid JSON ({e}); fix or remove it") from e
    if not isinstance(data, dict) or not isinstance(data.get("files"), dict):
        raise InstallError(f"{cfg.manifest_path} has no 'files' map; fix or remove it")
    return data


def owned_paths(cfg: Config, manifest: dict | None) -> tuple[dict[Path, dict], list[str]]:
    """Manifest entries the installer may touch (only under GENESIS_HOME or ~/.kiro/agents)."""
    out: dict[Path, dict] = {}
    warnings: list[str] = []
    for raw, meta in ((manifest or {}).get("files") or {}).items():
        p = Path(raw)
        if p.is_absolute() and (_under(p, cfg.home) or p.parent == cfg.agents_dir) and p != cfg.manifest_path:
            out[p] = meta if isinstance(meta, dict) else {}
        else:
            warnings.append(f"manifest entry {raw!r} is outside the installation roots — ignored")
    return out, warnings


@dataclass
class Plan:
    added: list[Path] = field(default_factory=list)
    changed: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)
    unchanged: list[Path] = field(default_factory=list)
    adopted: list[Path] = field(default_factory=list)     # identical foreign file → taken into the manifest
    conflicts: list[Path] = field(default_factory=list)   # foreign files we would overwrite / collide with
    local_edits: list[Path] = field(default_factory=list)  # owned files edited since the last install
    warnings: list[str] = field(default_factory=list)

    @property
    def writes(self) -> bool:
        return bool(self.added or self.changed or self.removed or self.adopted or self.conflicts)


def _mode(p: Path) -> int:
    return p.stat().st_mode & 0o777


def compute_plan(cfg: Config, desired: dict[Path, Item], manifest: dict | None) -> Plan:
    plan = Plan()
    owned, plan.warnings = owned_paths(cfg, manifest)
    for dest, item in sorted(desired.items()):
        if not dest.exists():
            plan.added.append(dest)
            continue
        if not dest.is_file():
            raise InstallError(f"{dest} exists and is not a regular file")
        current = dest.read_bytes()
        if dest in owned:
            if owned[dest].get("sha256") not in (None, sha256(current)):
                plan.local_edits.append(dest)
            if current == item.data and _mode(dest) == item.mode:
                plan.unchanged.append(dest)
            else:
                plan.changed.append(dest)
        elif current == item.data:
            plan.adopted.append(dest)
        else:
            plan.conflicts.append(dest)
    # A same-named agent in another format (genesis-dev.md next to our genesis-dev.json) would collide.
    stems = {d.stem for d in desired if d.parent == cfg.agents_dir}
    if cfg.agents_dir.is_dir():
        for p in sorted(cfg.agents_dir.iterdir()):
            if p in desired or p in owned or not p.name.startswith("genesis-") or p.suffix not in AGENT_SUFFIXES:
                continue
            if p.stem in stems:
                plan.conflicts.append(p)
            else:
                plan.warnings.append(f"{_tilde(p)} is a genesis-* agent the installer does not own (left alone)")
    for p in sorted(set(owned) - set(desired)):
        if p.exists():
            plan.removed.append(p)
    return plan


# ── apply ──────────────────────────────────────────────────────────────────────────────────────────────────────


def _atomic_write(dest: Path, data: bytes, mode: int) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{dest.name}.", dir=dest.parent)
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, mode)
        os.replace(tmp, dest)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


class Backup:
    """Lazily creates {{GENESIS_HOME}}/backups/<timestamp>/ and mirrors each file's path below it."""

    def __init__(self, cfg: Config):
        self.cfg = cfg
        self.dir: Path | None = None

    def save(self, p: Path) -> None:
        if self.dir is None:
            stamp = _dt.datetime.now().strftime("%Y%m%d-%H%M%S")
            base = self.cfg.home / "backups" / stamp
            d, n = base, 1
            while d.exists():
                n += 1
                d = base.with_name(f"{stamp}-{n}")
            d.mkdir(parents=True)
            self.dir = d
        home = Path.home()
        rel = p.relative_to(home) if _under(p, home) else Path("_abs") / p.relative_to(p.anchor)
        target = self.dir / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, target)


def _prune_empty(p: Path, cfg: Config) -> None:
    d = p.parent
    while _under(d, cfg.home) and d != cfg.home and d.is_dir() and not any(d.iterdir()):
        d.rmdir()
        d = d.parent


def source_revision(cfg: Config) -> dict:
    def git(*args: str) -> str | None:
        try:
            r = subprocess.run(["git", "-C", str(cfg.source), *args], capture_output=True, text=True, timeout=20)
        except (OSError, subprocess.SubprocessError):
            return None
        return r.stdout.strip() if r.returncode == 0 else None

    commit = git("rev-parse", "--short", "HEAD")
    status = git("status", "--porcelain", "--", ".") if commit else None
    return {"tracker": str(cfg.tracker), "agent_system": str(cfg.source), "commit": commit,
            "dirty": (bool(status) if status is not None else None)}


def build_manifest(cfg: Config, desired: dict[Path, Item]) -> dict:
    return {
        "manifest_version": MANIFEST_VERSION,
        "installed_at": _dt.datetime.now().astimezone().isoformat(timespec="seconds"),
        "source": source_revision(cfg),
        "values": cfg.values(),
        "repos": str(cfg.repos),  # read by genesis-ctx (config.default_repos)
        "genesis_home": str(cfg.home),
        "agents_dir": str(cfg.agents_dir),
        "files": {str(p): {"sha256": sha256(i.data), "mode": f"{i.mode:04o}", "source": i.source}
                  for p, i in sorted(desired.items())},
    }


def apply_plan(cfg: Config, desired: dict[Path, Item], plan: Plan, force: bool) -> Path | None:
    backup = Backup(cfg)
    for p in plan.changed + plan.removed + (plan.conflicts if force else []):
        if p.exists():
            backup.save(p)
    for p in plan.conflicts:
        if p not in desired:  # a same-named agent in another format: backed up above, now removed
            p.unlink()
    for p in plan.added + plan.changed + [c for c in plan.conflicts if c in desired] + plan.adopted:
        _atomic_write(p, desired[p].data, desired[p].mode)
    for p in plan.removed:
        p.unlink()
        _prune_empty(p, cfg)
    return backup.dir


# ── preflight ──────────────────────────────────────────────────────────────────────────────────────────────────


@dataclass
class Preflight:
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)


def _run(cmd: list[str]) -> tuple[int, str]:
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError) as e:
        return 127, str(e)
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def preflight(cfg: Config) -> Preflight:
    pf = Preflight()
    v = sys.version_info
    if v < (3, 11):
        pf.errors.append(f"python {v.major}.{v.minor} found; genesis-ctx needs Python >= 3.11")
    else:
        pf.notes.append(f"python {v.major}.{v.minor}.{v.micro}")
    if shutil.which("git"):
        pf.notes.append("git")
    else:
        pf.errors.append("git not found on PATH")
    for sub in ("agents", "skills", "hooks"):
        if not (cfg.source / sub).is_dir():
            pf.errors.append(f"source {cfg.source}/{sub}/ missing")
    if not (cfg.tracker / "agent-system" / "tools" / "genesis-ctx").is_file():
        pf.errors.append(f"TRACKER={cfg.tracker} has no agent-system/tools/genesis-ctx (is it project-tracker/genesis?)")
    if not cfg.repos.is_dir():
        pf.errors.append(f"REPOS={cfg.repos} does not exist")
    else:
        missing = [n for n in REPO_NAMES if not (cfg.repos / n).is_dir()]
        if missing:
            pf.errors.append(f"REPOS={cfg.repos} is missing: {', '.join(missing)}")
        else:
            pf.notes.append(f"{len(REPO_NAMES)} repos")
    _engine_check(pf)
    return pf


def _engine_check(pf: Preflight) -> None:
    """The profiles use the V3 format (permissions.rules); they need the V3 engine. Warn — never fail — otherwise."""
    kiro = os.environ.get("GENESIS_KIRO_CLI") or shutil.which("kiro-cli")
    if not kiro:
        pf.warnings.append("kiro-cli not found — the agents need Kiro CLI with the V3 engine")
        return
    rc, out = _run([kiro, "--version"])
    m = re.search(r"(\d+)\.(\d+)\.(\d+)", out)
    version = m.group(0) if m else "unknown"
    if m and int(m.group(1)) >= 3:
        pf.notes.append(f"kiro-cli {version} (V3)")
        return
    rc, help_all = _run([kiro, "--help-all"])
    if "--v3" not in help_all:
        pf.warnings.append(f"kiro-cli {version} has no V3 engine — profiles need CLI 3 (they will not load on 2.x)")
        return
    _, engine = _run([kiro, "settings", "chat.agentEngine"])
    engine = engine.strip().strip('"')
    if engine == "v3":
        pf.notes.append(f"kiro-cli {version} + V3 engine (chat.agentEngine=v3: plain `kiro-cli` launches V3)")
    else:
        pf.notes.append(f"kiro-cli {version} + V3 engine (launch with `kiro-cli --v3 …`; chat.agentEngine not v3)")


