def _print_plan(cfg: Config, desired: dict[Path, Item], plan: Plan, diffs: bool) -> None:
    n = len
    print(f"Plan: {n(plan.added)} added · {n(plan.changed)} changed · {n(plan.removed)} removed · "
          f"{n(plan.unchanged) + n(plan.adopted)} unchanged"
          + (f" · {n(plan.conflicts)} FOREIGN" if plan.conflicts else ""))
    for label, sym, paths in (("added", "+", plan.added), ("changed", "~", plan.changed),
                              ("removed", "-", plan.removed), ("adopted (identical, now owned)", "=", plan.adopted),
                              ("foreign (not installed by Genesis)", "!", plan.conflicts)):
        for p in paths:
            src = desired[p].source if p in desired else ""
            print(f"  {sym} {_tilde(p)}" + (f"   ← {src}" if src else "") + ("" if label in ("added", "changed",
                  "removed") else f"   [{label}]"))
    for p in plan.local_edits:
        print(f"  note: {_tilde(p)} was edited after the last install — the edit is backed up, then replaced")
    for w in plan.warnings:
        print(f"  warning: {w}")
    if diffs:
        for p in plan.changed + [c for c in plan.conflicts if c in desired]:
            old, new = p.read_bytes(), desired[p].data
            if old == new:
                print(f"\n  {_tilde(p)}: mode {_mode(p):04o} → {desired[p].mode:04o}")
                continue
            try:
                a, b = old.decode("utf-8").splitlines(True), new.decode("utf-8").splitlines(True)
            except UnicodeDecodeError:
                print(f"\n  {_tilde(p)}: binary content differs")
                continue
            sys.stdout.writelines(difflib.unified_diff(a, b, f"{_tilde(p)} (installed)", f"{_tilde(p)} (new)"))


def _summary(desired: dict[Path, Item], cfg: Config) -> str:
    agents = sum(1 for p in desired if p.parent == cfg.agents_dir)
    skills = len({p.relative_to(cfg.home / "skills").parts[0] for p in desired if _under(p, cfg.home / "skills")})
    hooks = sum(1 for p in desired if p.parent == cfg.home / "hooks")
    return f"{agents} profiles, {skills} skills, {hooks} hooks, 1 shim ({len(desired)} files)"


def cmd_sync(cfg: Config, *, mode: str, dry_run: bool, force: bool, pull: bool) -> int:
    print(f"Genesis agent installer — {mode}{' (dry run)' if dry_run else ''}")
    manifest = read_manifest(cfg)
    if mode == "update" and manifest is None:
        print(f"Not installed ({_tilde(cfg.manifest_path)} missing) — run install.sh first.", file=sys.stderr)
        return 1
    if pull:
        if dry_run:
            print(f"(dry run: would run `git -C {cfg.tracker} pull --rebase` first)")
        else:
            rc, out = _run(["git", "-C", str(cfg.tracker), "pull", "--rebase"])
            print(out.rstrip())
            if rc != 0:
                print("git pull --rebase failed — nothing installed.", file=sys.stderr)
                return 1
    rev = source_revision(cfg)
    print(f"Source:  {cfg.source} @ {rev['commit'] or 'no git'}"
          + ("" if rev["dirty"] is None else (" (uncommitted changes)" if rev["dirty"] else " (clean)")))
    print(f"Values:  TRACKER={cfg.tracker}\n         REPOS={cfg.repos}\n         GENESIS_HOME={cfg.home}\n"
          f"         MODEL={cfg.model or '(as in each profile)'}")
    pf = preflight(cfg)
    print("Preflight: " + ("FAILED" if pf.errors else "ok") + " — " + " · ".join(pf.notes))
    for w in pf.warnings:
        print(f"  warning: {w}")
    for e in pf.errors:
        print(f"  error: {e}", file=sys.stderr)
    if pf.errors:
        return 1
    desired = build_desired(cfg)
    errors = validate(cfg, desired)
    if errors:
        print(f"Validation: FAILED — {len(errors)} problem(s); nothing written.", file=sys.stderr)
        for e in errors:
            print(f"  error: {e}", file=sys.stderr)
        return 1
    print(f"Validation: ok — {_summary(desired, cfg)}")
    plan = compute_plan(cfg, desired, manifest)
    _print_plan(cfg, desired, plan, diffs=dry_run)
    if plan.conflicts and not force:
        print(f"Refusing: {len(plan.conflicts)} file(s) above were not installed by Genesis (not in the manifest). "
              "Move them away, or re-run with --force to back them up and replace them.", file=sys.stderr)
        return 1
    manifest_stale = manifest is None or set(manifest.get("files", {})) != {str(p) for p in desired} or \
        manifest.get("values") != cfg.values()
    if not plan.writes and not manifest_stale:
        print("Nothing to change — the installation is up to date.")
        return 0
    if dry_run:
        print("Dry run — nothing written.")
        return 0
    backup_dir = apply_plan(cfg, desired, plan, force)
    _atomic_write(cfg.manifest_path, (json.dumps(build_manifest(cfg, desired), indent=2) + "\n").encode(), 0o644)
    print(f"Done. Manifest: {_tilde(cfg.manifest_path)}" + (f" · backups: {_tilde(backup_dir)}" if backup_dir else ""))
    if mode == "install":
        print(f"Optional, for your own terminal only (agents call it by absolute path): "
              f"export PATH=\"{cfg.home}/bin:$PATH\"")
    print("Running Kiro sessions hot-reload profiles; start a new session to be sure.")
    return 0


def cmd_uninstall(cfg: Config, *, dry_run: bool) -> int:
    print(f"Genesis agent installer — uninstall{' (dry run)' if dry_run else ''}")
    manifest = read_manifest(cfg)
    if manifest is None:
        print(f"Nothing installed ({_tilde(cfg.manifest_path)} missing).")
        return 0
    owned, warnings = owned_paths(cfg, manifest)
    present = sorted(p for p in owned if p.exists())
    print(f"Plan: {len(present)} removed (+ the manifest); backups/ kept")
    for p in present:
        print(f"  - {_tilde(p)}")
    for w in warnings:
        print(f"  warning: {w}")
    if dry_run:
        print("Dry run — nothing removed.")
        return 0
    backup = Backup(cfg)
    for p in present + [cfg.manifest_path]:
        backup.save(p)
    for p in present:
        p.unlink()
        _prune_empty(p, cfg)
    cfg.manifest_path.unlink()
    print(f"Done. Backups: {_tilde(backup.dir) if backup.dir else '-'}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="genesis-installer", description="Install / update / uninstall the Genesis "
                                "agents, skills and hooks (Phase 47, 47-07). Stdlib only.")
    p.add_argument("--source", type=Path, help="agent-system/ directory (default: this installer's)")
    p.add_argument("--conf", type=Path, help="config file (default: <source>/install.conf, optional)")
    sub = p.add_subparsers(dest="cmd", required=True, metavar="COMMAND")
    s = sub.add_parser("install", help="preflight → render → validate → plan → copy → manifest")
    s.add_argument("--dry-run", action="store_true")
    s.add_argument("--force", action="store_true", help="back up and replace foreign files")
    s = sub.add_parser("update", help="re-render and apply only the differences")
    s.add_argument("--dry-run", action="store_true")
    s.add_argument("--force", action="store_true", help="back up and replace foreign files")
    s.add_argument("--pull", action="store_true", help="git pull --rebase project-tracker first")
    s = sub.add_parser("uninstall", help="remove exactly the manifest's files (backed up first)")
    s.add_argument("--dry-run", action="store_true")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        cfg = load_config(args.source, args.conf)
        if args.cmd == "uninstall":
            return cmd_uninstall(cfg, dry_run=args.dry_run)
        return cmd_sync(cfg, mode=args.cmd, dry_run=args.dry_run, force=args.force,
                        pull=getattr(args, "pull", False))
    except InstallError as e:
        print(f"genesis-installer: {e}", file=sys.stderr)
        return 2
