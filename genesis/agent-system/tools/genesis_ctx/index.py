"""index: regenerate context/_generated/* and fill / refresh reviewed_fp (47-03 §3)."""
from __future__ import annotations

from pathlib import Path

from . import md, tomlio
from .config import CtxError, Ctx, read
from .model import Corpus
from .query import area_line

GEN_NOTE = "<!-- generated by `genesis-ctx index` — do not edit (47-02 §2) -->"


def _short(ids) -> str:
    return ",".join(i.split("-")[1] for i in ids)


def adr_digest(c: Corpus) -> str:
    out = [GEN_NOTE, "# ADR digest — one line per ADR",
           "", "Full text: `genesis-ctx adr <ID>` (loads the amendment chain). Untagged = not yet routed (47-05).", ""]
    for i in c.adr_ids:
        t = c.adr_tags.get(i)
        if not t:
            out.append(f"- {i} [untagged] — {c.adr_title(i)}")
            continue
        rels = []
        if t.get("amends"):
            rels.append("amends " + _short(t["amends"]))
        if t.get("amended_by"):
            rels.append("amended by " + _short(t["amended_by"]))
        if t.get("superseded_by"):
            rels.append("superseded by " + _short([t["superseded_by"]]))
        status = t.get("status", "")
        flag = f" {{{status}}}" if status and status not in ("accepted",) else ""
        rel = f" ({'; '.join(rels)})" if rels else ""
        out.append(f"- {i} [{','.join(t.get('areas', []) or [])}]{flag}{rel} — {c.adr_rule(i) or c.adr_title(i)}")
    return "\n".join(out) + "\n"


def lesson_digest(c: Corpus) -> str:
    out = [GEN_NOTE, "# Lesson digest — one line per hard-won lesson (bible/06 §7)",
           "", "Full text: `genesis-ctx lesson <ID>`.", ""]
    for n, l in enumerate(c.lessons, 1):
        if not l.marker:
            out.append(f"- (unmarked #{n}) [untagged] — {l.lead or md.collapse(l.text)[:160]}")
            continue
        t = c.lesson_tags.get(l.marker)
        tag = f"[{','.join(t.get('areas', []) or [])}]" if t else "[untagged]"
        out.append(f"- {l.marker} {tag} — {c.lesson_rule(l.marker)}")
    return "\n".join(out) + "\n"


def area_catalog(c: Corpus) -> str:
    out = [GEN_NOTE, "# Area catalog — one line per area (context/areas.toml)",
           "", "Detail: `genesis-ctx area <name>`. Always-on areas are part of every pack.", ""]
    out += ["- " + area_line(n, c.areas[n]) for n in sorted(c.areas)]
    return "\n".join(out) + "\n"


def generated(c: Corpus) -> dict[str, str]:
    return {"adr-digest.md": adr_digest(c), "lesson-digest.md": lesson_digest(c), "area-catalog.md": area_catalog(c)}


def stale_generated(ctx: Ctx, c: Corpus) -> list[str]:
    return [name for name, text in generated(c).items() if read(ctx.generated_dir / name) != text]


def update_fps(ctx: Ctx, c: Corpus, reviewed: list[str], reviewed_all: bool) -> list[str]:
    """Write reviewed_fp in place: fill empty ones; refresh the ids in `reviewed` (or all)."""
    changed: list[str] = []
    wanted = set()
    for r in reviewed:
        i = md.parse_adr_id(r) if r.upper().startswith("ADR") else md.parse_lesson_id(r)
        if not i:
            raise CtxError(f"not an ADR or lesson id: {r}")
        wanted.add(i)
    missing = sorted(w for w in wanted if w not in (c.adr_tags if w.startswith("ADR-") else c.lesson_tags))
    if missing:
        raise CtxError(f"no tag entry for: {', '.join(missing)}")
    for fname, tags, fp_of, known in (
        ("adr.toml", c.adr_tags, c.adr_fp, c.adr_known),
        ("lesson.toml", c.lesson_tags, c.lesson_fp, lambda i: c.lesson(i) is not None),
    ):
        path = ctx.tags_dir / fname
        text = read(path)
        new = text
        for i, t in tags.items():
            if not known(i):
                continue
            cur = fp_of(i)
            old = (t.get("reviewed_fp") or "").strip()
            if (not old or reviewed_all or i in wanted) and old != cur:
                new = tomlio.set_field(new, i, "reviewed_fp", cur)
                changed.append(i)
        if new != text:
            path.write_text(new, encoding="utf-8")
    return changed


def cmd_index(ctx: Ctx, reviewed: list[str] | None = None, reviewed_all: bool = False) -> int:
    c = Corpus(ctx)
    changed = update_fps(ctx, c, reviewed or [], reviewed_all)
    if changed:
        c = Corpus(ctx)  # re-read the tag files
    ctx.generated_dir.mkdir(parents=True, exist_ok=True)
    wrote = []
    for name, text in generated(c).items():
        p: Path = ctx.generated_dir / name
        if read(p) != text:
            p.write_text(text, encoding="utf-8")
            wrote.append(name)
    print(f"index: {len(wrote)} generated file(s) rewritten" + (f" ({', '.join(wrote)})" if wrote else ""))
    print(f"index: reviewed_fp written for {len(changed)} tag(s)" + (f": {', '.join(changed)}" if changed else ""))
    u = c.untagged_counts()
    if any(u.values()):
        print(f"index: untagged — {u['adrs']} ADRs, {u['lessons']} lessons, {u['sections']} code-map sections")
    return 0
